import assert from 'node:assert/strict';
import fs from 'node:fs';
import test from 'node:test';
const source = name => fs.readFileSync(new URL('../src/' + name, import.meta.url), 'utf8');
test('shared branding uses transparent logo marks in application and public landing', () => {
  assert.match(source('BrandLogo.vue'), /\/brand\/logo-mark\.svg/);
  assert.match(source('BrandLogo.vue'), /\/brand\/logo-full\.svg/);
  assert.match(source('App.vue'), /<BrandLogo icon \/>/);
  assert.match(source('MarketingLanding.vue'), /<BrandLogo icon\/>/);
  assert.doesNotMatch(source('MarketingLanding.vue'), /<BrandLogo \/>/);
  assert.doesNotMatch(source('App.vue'), />SM<\/span>/);
});
test('pricing uses the current catalogue and existing selection handlers', () => {
  assert.match(source('App.vue'), /<ServicePricing :plans="activeServicePlans"[^>]*:current-plan="currentServicePlanCode"/);
  assert.match(source('App.vue'), /@select="selectServicePlan"/);
  assert.match(source('ServicePricing.vue'), /plan\.price/);
  assert.match(source('ServicePricing.vue'), /plan\.max_channels/);
  assert.match(source('ServicePricing.vue'), /v-if="mode !== 'chatbot'" class="smh-price-quota"/);
  assert.match(source('ServicePricing.vue'), /plan\?\.max_rag_chunks/);
  assert.match(source('ServicePricing.vue'), /knowledgeLimit:'Mục kiến thức tối đa'/);
  assert.match(source('App.vue'), /max_rag_chunks: 10000/);
  assert.match(source('ServicePricing.vue'), /function isDowngrade\(plan\)/);
  assert.match(source('ServicePricing.vue'), /planChangeKind\(current, plan\) === 'downgrade'/);
  assert.match(source('ServicePricing.vue'), /downgradeUnavailable:props\.mode === 'chatbot' \? 'Không hỗ trợ hạ trợ lý' : 'Không hỗ trợ hạ gói'/);
  assert.match(source('ServicePricing.vue'), /:disabled="authenticated && \(currentPlan === plan\.code \|\| isDowngrade\(plan\)\)"/);
  assert.doesNotMatch(source('ServicePricing.vue'), /Hạ gói xuống|Hạ trợ lý xuống/);
  assert.match(source('ServicePricing.vue'), /if \(!current\) return `\$\{copy\.value\.chooseChatbot\} \$\{targetName\}`/);
  assert.match(source('ServicePricing.vue'), /selectedChatbot:'Bot đang chọn'/);
  assert.match(source('ServicePricing.vue'), /if \(isChatbot && props\.selected === plan\.code\) return copy\.value\.selectedChatbot/);
  assert.match(source('ServicePricing.vue'), /upgradeChatbot:'Nâng cấp lên'/);
  assert.match(source('ServicePricing.vue'), /const selectedLabel = computed\(\(\)=>props\.mode === 'chatbot' \? copy\.value\.selectedChatbot : copy\.value\.selected\)/);
  assert.match(source('ServicePricing.vue'), /props\.mode === 'chatbot' \? 'One full-service chatbot plan'/);
  assert.match(source('ServicePricing.vue'), /props\.mode === 'chatbot' \? 'Một gói Trợ lý Toàn diện'/);
  assert.match(source('ServicePricing.vue'), /class="current-plan-label">\{\{ currentLabel \}\}/);
  assert.match(source('ServicePricing.vue'), /:disabled="authenticated && \(currentPlan === plan\.code \|\| isDowngrade\(plan\)\)"/);
  assert.match(source('ServicePricing.vue'), /:aria-pressed=/);
  assert.match(source('ServicePricing.vue'), /@media\(max-width:600px\)/);
  assert.match(source('ServicePricing.vue'), /props\.plans\.filter\(plan => plan\.code === 'pro'\)\.slice\(0, 1\)/);
  assert.match(source('ServicePricing.vue'), /fullName:'Trợ lý Toàn diện'/);
  assert.match(source('ServicePricing.vue'), /managedFee:'Không thu phí cài đặt riêng'/);
  assert.match(source('ServicePricing.vue'), /Cài đặt ban đầu đã nằm trong gói Trợ lý Toàn diện/);
  assert.match(source('ServicePricing.vue'), /v-if="mode === 'chatbot'" class="smh-managed-service"/);
  assert.match(source('ServicePricing.vue'), /managedKnowledge:'Nạp kiến thức'/);
  assert.match(source('App.vue'), /chatbot_rental_price: 3000000/);
  assert.match(source('ServicePricing.vue'), /\.smh-pricing\.is-chatbot \{ max-width:1080px; \}/);
  assert.match(source('ServicePricing.vue'), /grid-template-areas:"top benefits"/);
  assert.match(source('ServicePricing.vue'), /@media\(max-width:900px\)/);
});
