// ponytail: untranslated strings fall back to Vietnamese; add entries as screens are localized.
export function t(text) {
  if (typeof text !== "string") return text;
  if (locale.value !== "en") return standardizeVietnameseUiCopy(text);
  const key = text.replace(/\s+/g, " ").trim();
  const translated = english[key] || english[text];
  const leading = text.match(/^\s*/)?.[0] || "";
  const trailing = text.match(/\s*$/)?.[0] || "";
  if (translated) return `${leading}${standardizeEnglishUiCopy(translated)}${trailing}`;

  const quotaNotice = key.match(/^Gói đã chọn cho phép kết nối tối đa (.+?) nền tảng\. Việc kết nối thực tế được thực hiện duy nhất tại mục Kết nối mạng xã hội\.$/);
  if (quotaNotice) return `The selected plan allows up to ${quotaNotice[1]} platforms. Connect platforms from Social Connections.`;
  const details = key.match(/^Xem chi tiết \((\d+) hoạt động gần nhất\)$/);
  if (details) return `View details (${details[1]} recent activities)`;
  const payments = key.match(/^Lịch sử thu \((\d+)\)$/);
  if (payments) return `Payment history (${payments[1]})`;

  const content = text.slice(leading.length, text.length - trailing.length);
  const prefix = dynamicPrefixes.find(([source]) => content.startsWith(source));
  return prefix
    ? `${leading}${standardizeEnglishUiCopy(`${prefix[1]}${content.slice(prefix[0].length)}`)}${trailing}`
    : standardizeEnglishUiCopy(text);
}

const activeLocale = () => locale.value === "en" ? "en-US" : "vi-VN";

export function formatMoney(value) {
  return new Intl.NumberFormat(activeLocale(), {
    style: "currency",
    currency: "VND",
    maximumFractionDigits: 2,
  }).format(Number(value) || 0);
}

export function formatDateTime(value, options = { dateStyle: "medium", timeStyle: "short" }) {
  if (!value) return "—";
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? "—" : new Intl.DateTimeFormat(activeLocale(), options).format(date);
}

export function formatDate(value) {
  if (!value) return "—";
  const date = new Date(/^\d{4}-\d{2}-\d{2}$/.test(String(value)) ? `${value}T00:00:00` : value);
  return Number.isNaN(date.getTime()) ? "—" : new Intl.DateTimeFormat(activeLocale(), { dateStyle: "medium" }).format(date);
}

export function setLocale(nextLocale) {
  if (!supportedLocales.includes(nextLocale)) return false;
  locale.value = nextLocale;
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, nextLocale);
  } catch {
    // Keep the selected language for this session if browser storage is unavailable.
  }
  if (typeof document !== "undefined") document.documentElement.lang = nextLocale;
  return true;
}
